/**
 * Build-time fact pipeline. Owner: architect. See docs/architecture.md §5 and
 * docs/decisions/0003-build-time-fact-pipeline.md.
 *
 *   node scripts/facts/collect.ts            collect, render intro, write src/generated/
 *   node scripts/facts/collect.ts --strict   also refuse dirty trees, missing groups, !draft
 *   node scripts/facts/collect.ts --check    write nothing; fail if src/generated/ is stale
 *
 * Strict mode is on automatically when CI=true or FACTS_STRICT=1.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Facts } from '../../src/facts/schema.ts';
import { PATHS, ROOT } from './config.ts';
import { FactsError } from './errors.ts';
import { collectGit } from './git.ts';
import { collectAgents, collectPhases, collectProvenance, collectStack } from './sources.ts';
import { renderIntro } from './template.ts';

const args = new Set(process.argv.slice(2));
const strict =
  args.has('--strict') || process.env.CI === 'true' || process.env.FACTS_STRICT === '1';
const checkOnly = args.has('--check');

function collectFacts(): Facts {
  const { source, git, bodies } = collectGit();
  const phases = collectPhases();
  const provenance = collectProvenance(bodies);

  const unavailable: Record<string, string> = {};
  if ('unavailable' in phases) unavailable.phases = phases.unavailable;
  if ('unavailable' in provenance) unavailable.provenance = provenance.unavailable;

  return {
    schemaVersion: 1,
    source,
    git,
    stack: collectStack(),
    agents: collectAgents(),
    phases: 'value' in phases ? phases.value : null,
    provenance: 'value' in provenance ? provenance.value : null,
    unavailable,
  };
}

function strictChecks(facts: Facts): string[] {
  const problems: string[] = [];
  if (facts.source.dirty) {
    problems.push(
      'working tree has uncommitted changes; "as of commit" facts would not match the bundle',
    );
  }
  for (const [group, reason] of Object.entries(facts.unavailable)) {
    problems.push(`fact group "${group}" is unavailable: ${reason}`);
  }
  if (facts.provenance && facts.provenance.modelCoAuthoredCommitCount === 0) {
    problems.push(
      `no commit has a "Co-Authored-By: ${facts.provenance.model}" trailer; provenance is unverified`,
    );
  }
  return problems;
}

function moduleSource(
  typeName: 'Facts' | 'ResolvedIntro',
  exportName: string,
  json: string,
): string {
  return (
    '// Generated by scripts/facts/collect.ts. Do not edit; run "npm run facts".\n' +
    `import type { ${typeName} } from '@/facts/schema';\n\n` +
    `export const ${exportName}: ${typeName} = ${json};\n`
  );
}

function main(): void {
  const facts = collectFacts();

  if (strict) {
    const problems = strictChecks(facts);
    if (problems.length > 0) {
      throw new FactsError(
        `Strict facts check failed:\n${problems.map((p) => `  - ${p}`).join('\n')}`,
      );
    }
  } else {
    for (const [group, reason] of Object.entries(facts.unavailable)) {
      console.warn(
        `[facts] warning: "${group}" unavailable (${reason}); any template use will fail.`,
      );
    }
    if (facts.source.dirty)
      console.warn(`[facts] note: uncommitted changes; revision is ${facts.source.revision}.`);
  }

  const templatePath = join(ROOT, PATHS.introTemplate);
  if (!existsSync(templatePath))
    throw new FactsError(`Intro template is missing: ${PATHS.introTemplate}`);
  const intro = renderIntro(readFileSync(templatePath, 'utf8'), facts, {
    strict,
    file: PATHS.introTemplate,
  });
  if (intro.draft)
    console.warn(`[facts] warning: ${PATHS.introTemplate} is !draft; FR-12 coverage not enforced.`);

  const factsJson = JSON.stringify(facts, null, 2);
  const introJson = JSON.stringify(intro, null, 2);
  const outputs: Record<string, string> = {
    'facts.json': `${factsJson}\n`,
    'intro.json': `${introJson}\n`,
    'facts.ts': moduleSource('Facts', 'facts', factsJson),
    'intro.ts': moduleSource('ResolvedIntro', 'intro', introJson),
  };

  const outDir = join(ROOT, PATHS.outDir);
  const stale: string[] = [];
  if (!checkOnly) mkdirSync(outDir, { recursive: true });
  for (const [name, content] of Object.entries(outputs)) {
    const path = join(outDir, name);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current === content) continue;
    if (checkOnly) stale.push(name);
    else writeFileSync(path, content);
  }

  if (stale.length > 0) {
    throw new FactsError(`Generated facts are stale (${stale.join(', ')}). Run "npm run facts".`);
  }

  console.log(
    `[facts] ${checkOnly ? 'up to date' : 'ok'}: as of commit ${facts.source.revision}, ` +
      `${facts.git.commitCount} commits, ${facts.agents.count} agents, ` +
      `${intro.pages.length} intro page(s), ${intro.factKeys.length} fact key(s)${strict ? ' [strict]' : ''}.`,
  );
}

try {
  main();
} catch (error) {
  if (error instanceof FactsError) {
    console.error(`\n[facts] BUILD STOPPED: ${error.message}\n`);
    process.exit(1);
  }
  throw error;
}
